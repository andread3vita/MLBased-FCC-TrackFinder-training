"""SE(3)-equivariance test for both algebra arms.

The acceptance criterion for the projective port. A rigid motion acts on
multivectors by the sandwich product with a versor, so for an equivariant model

    embed(g x)       == U embed(x) U~         (the hit embeddings)
    backbone(U m U~) == U backbone(m) U~      (the transformer stack)

Both are checked, under rotations *and* translations, for every arm. The
embedding check catches a wrong point or line convention; the backbone check
catches a wrong equivariant basis, join, or attention.

Testing translations separately matters: rotations fix the null directions of
both algebras, so a wrong choice of null direction in the equivariant basis, or
a distance feature built on the wrong components, still passes a rotation test
and only shows up under translation.

The translation check covers the backbone only. `embed` is knowingly not
translation equivariant -- it rescales positions by a fixed length and then L2
normalizes each hit multivector, on the grounds that the interaction point is a
physically meaningful origin. That choice is about the inputs; the hidden layers
are still supposed to respect the full rigid-motion group, and that is what is
checked here.

    CUDA_VISIBLE_DEVICES= python -m src.eval.test_equivariance
"""

import argparse
import math

import torch

from src.eval.smoke_arms import base_args
from src.model import CGATrParquetModel


def blade_index(model, name, tup):
    """Index of a blade. The conformal tables name blades by tuple, the
    projective ones by string, so accept either."""
    for i, nm in enumerate(model._blade_names):
        if nm == name or (isinstance(nm, tuple) and nm == tup):
            return i
    raise LookupError(f"no {name} blade in {model._blade_names}")


def rotor(model, theta):
    """Rotor for a rotation by `theta` in the e1-e2 plane."""
    r = torch.zeros(model.num_blades, dtype=torch.float64)
    r[0] = math.cos(theta / 2.0)
    r[blade_index(model, "e12", (1, 2))] = -math.sin(theta / 2.0)
    return r


def translator(model, t):
    """Versor for a translation by `t`, T = 1 - (t^n)/2 for the null direction n.

    n is the degenerate vector e0 in the projective algebra and the point at
    infinity e- - e+ in the conformal one -- the same directions the equivariant
    linear basis is built from, so this is the translation the network is
    supposed to respect.
    """
    gp = model.basis_gp.to(torch.float64)
    n = torch.zeros(model.num_blades, dtype=torch.float64)
    if model.projective:
        n[blade_index(model, "e0", (0,))] = 1.0
        spatial = [blade_index(model, f"e{i}", (i,)) for i in (1, 2, 3)]
    else:
        # Conformal: translations are generated by the point at infinity
        # inf = e- - e+, fixed by the embedding P = o + p + |p|^2 inf/2 in
        # interface/point.py (o = (e+ + e-)/2). The other null direction, o
        # itself, generates transversions instead.
        n[4] = -1.0
        n[5] = 1.0
        spatial = [1, 2, 3]

    tv = torch.zeros(model.num_blades, dtype=torch.float64)
    for idx, ti in zip(spatial, t):
        tv[idx] = float(ti)

    versor = torch.zeros(model.num_blades, dtype=torch.float64)
    versor[0] = 1.0
    # t and n are orthogonal, so their geometric product is the bivector t^n.
    return versor - 0.5 * torch.einsum("ijk,j,k->i", gp, tv, n)


def reverse(model, r):
    """Reverse of a multivector: grade k picks up (-1)^{k(k-1)/2}."""
    return r * model._reversal.to(r.dtype)


def sandwich(model, r, x):
    """R x R~ for a batch of multivectors x of shape (..., blades)."""
    gp = model.basis_gp.to(torch.float64)
    rt = reverse(model, r)
    rx = torch.einsum("ijk,j,...k->...i", gp, r, x.to(torch.float64))
    return torch.einsum("ijk,...j,k->...i", gp, rx, rt)


def rot_z(theta, x):
    c, s = math.cos(theta), math.sin(theta)
    R = torch.tensor([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]], dtype=x.dtype)
    return x @ R.T


def make_features(n, with_time, gen, with_drift_dir=False):
    """Half vertex hits, half drift hits, with plausible magnitudes."""
    n_cols = 10 + (1 if with_time else 0) + (3 if with_drift_dir else 0)
    f = torch.zeros(n, n_cols, dtype=torch.float64)
    n_vtx = n // 2
    f[:n_vtx, :3] = torch.randn(n_vtx, 3, generator=gen) * 100.0
    f[:n_vtx, 3] = 0.0
    f[n_vtx:, :3] = torch.randn(n - n_vtx, 3, generator=gen) * 1000.0
    f[n_vtx:, 3] = 1.0
    f[n_vtx:, 4:7] = torch.randn(n - n_vtx, 3, generator=gen) * 1000.0
    f[n_vtx:, 7] = torch.rand(n - n_vtx, generator=gen) * 5.0          # drift
    f[n_vtx:, 8] = torch.rand(n - n_vtx, generator=gen) * 2 * math.pi  # azimuth
    f[n_vtx:, 9] = torch.rand(n - n_vtx, generator=gen) * 0.1          # stereo
    if with_time:
        f[:, 10] = torch.randn(n, generator=gen) * 0.5
    if with_drift_dir:
        off = 11 if with_time else 10
        u = torch.randn(n - n_vtx, 3, generator=gen, dtype=torch.float64)
        f[n_vtx:, off:off + 3] = u / u.norm(dim=-1, keepdim=True)
    return f


def rotate_features(theta, f):
    """Rotate every geometric quantity in the feature block.

    The wire direction is built from the azimuth, so rotating about z is just a
    shift of that angle; positions rotate directly.
    """
    g = f.clone()
    g[:, :3] = rot_z(theta, f[:, :3])
    g[:, 4:7] = rot_z(theta, f[:, 4:7])
    g[:, 8] = f[:, 8] + theta
    # The drift direction, where present, is a vector and rotates with the rest.
    if f.shape[1] >= 13:
        off = f.shape[1] - 3
        g[:, off:off + 3] = rot_z(theta, f[:, off:off + 3])
    return g


def translate_features(t, f):
    """Shift the hit position and the wire reference point.

    Drift distance, wire azimuth and stereo angle are all translation
    invariant, so they carry over unchanged.
    """
    g = f.clone()
    tt = torch.as_tensor(t, dtype=f.dtype)
    g[:, :3] = f[:, :3] + tt
    g[:, 4:7] = f[:, 4:7] + tt
    return g


def check_backbone(model, name, versor, n=64, tol=2e-4):
    """Does the transformer stack commute with the versor?

    Driven with embedded hits so the multivectors are the kind the stack
    actually sees, but the versor is applied to those multivectors directly,
    bypassing the non-equivariant input scaling and normalization.
    """
    gen = torch.Generator().manual_seed(0)
    f = make_features(n, model.use_time, gen, model.needs_drift_dir)
    seq = [n]

    with torch.no_grad():
        mv, scalars = model.embed(f)
        mv_moved = sandwich(model, versor, mv)

        out = model.backbone(mv, scalars, seq)
        out_moved = model.backbone(mv_moved.to(mv.dtype), scalars, seq)

        want = sandwich(model, versor, out)
        err = (want - out_moved.to(torch.float64)).abs().max().item()
        scale = want.abs().max().item()

    rel = err / max(scale, 1e-9)
    ok = rel < tol
    print(f"  [{'ok' if ok else 'FAIL'}] {name:<22} backbone {rel:.2e}")
    return ok


def check_backbone_action(model, name, action, n=64, tol=2e-4):
    """Check the backbone against a linear blade-space group action."""
    gen = torch.Generator().manual_seed(0)
    f = make_features(n, model.use_time, gen, model.needs_drift_dir)
    seq = [n]

    def moved(x):
        return torch.einsum(
            "ij,...cj->...ci", action.to(torch.float64), x.to(torch.float64)
        )

    with torch.no_grad():
        mv, scalars = model.embed(f)
        mv_moved = moved(mv)
        out = model.backbone(mv, scalars, seq)
        out_moved = model.backbone(mv_moved.to(mv.dtype), scalars, seq)
        want = moved(out)
        err = (want - out_moved.to(torch.float64)).abs().max().item()
        scale = want.abs().max().item()

    rel = err / max(scale, 1e-9)
    ok = rel < tol
    print(f"  [{'ok' if ok else 'FAIL'}] {name:<22} backbone {rel:.2e}")
    return ok


def check(model, name, transform, versor, n=64, tol=2e-4):
    gen = torch.Generator().manual_seed(0)
    f = make_features(n, model.use_time, gen, model.needs_drift_dir)
    g = transform(f)
    r = versor

    with torch.no_grad():
        mv, scalars = model.embed(f)
        mv_rot, scalars_rot = model.embed(g)

        # 1. The embeddings must rotate with the rotor.
        want = sandwich(model, r, mv)
        emb_err = (want - mv_rot.to(torch.float64)).abs().max().item()
        scale = mv.abs().max().item()

        # 2. The backbone must commute with the rotor.
        seq = [n]
        out = model.backbone(mv, scalars, seq)
        out_rot = model.backbone(mv_rot, scalars_rot, seq)
        want_out = sandwich(model, r, out)
        bb_err = (want_out - out_rot.to(torch.float64)).abs().max().item()
        bb_scale = out.abs().max().item()

    rel_emb = emb_err / max(scale, 1e-9)
    rel_bb = bb_err / max(bb_scale, 1e-9)
    ok = rel_emb < tol and rel_bb < tol
    print(f"  [{'ok' if ok else 'FAIL'}] {name:<22} "
          f"embedding {rel_emb:.2e}   backbone {rel_bb:.2e}")
    return ok


def check_primitives(shift, tol=1e-6):
    """Do the conformal geometric primitives mean what they claim to?

    Two independent things are checked per primitive: the defining inner-product
    identity (is <P,S> really the point-to-sphere distance) and covariance of the
    embedding map (does translating an embedded sphere give the embedded
    translated sphere). The model-level tests above cannot see either, because
    they apply versors to already-embedded multivectors and rotations happen to
    leave the broken terms alone -- the original sphere's error is proportional
    to |p|^2, which no rotation changes.

    Both are reported with and without the fix, so the table doubles as the
    record of what --fix_cga_null buys.
    """
    from src.cgatr.interface.point import embed_point
    from src.cgatr.interface.sphere import embed_sphere
    from src.cgatr.interface.plane import embed_plane
    from src.cgatr.interface.circle import embed_circle_ipns
    from src.cgatr.primitives.invariants import compute_inner_product_mask, inner_product

    model = CGATrParquetModel(base_args()).eval().double()
    op = model.basis_outer.double()
    ipw = compute_inner_product_mask(model.basis_gp.double()).double()

    def ip(a, b):
        return inner_product(ipw, a.unsqueeze(1), b.unsqueeze(1)).squeeze()

    versor = translator(model, shift)
    t = torch.tensor(shift, dtype=torch.float64)

    def moved(x):
        return sandwich(model, versor, x.unsqueeze(1)).squeeze(1)

    gen = torch.Generator().manual_seed(21)
    p = torch.randn(3000, 3, generator=gen, dtype=torch.float64)
    c = torch.randn(3000, 3, generator=gen, dtype=torch.float64)
    r = torch.rand(3000, generator=gen, dtype=torch.float64) * 0.5 + 0.05
    n = torch.randn(3000, 3, generator=gen, dtype=torch.float64)
    n = n / n.norm(dim=-1, keepdim=True)

    P = embed_point(p)
    d2 = ((p - c) ** 2).sum(-1)
    d_plane = (n * c).sum(-1)

    rows = []
    for fix in (False, True):
        S = embed_sphere(c, r, fix_null=fix)
        pi = embed_plane(n, c, fix_null=fix)
        C = embed_circle_ipns(c, n, r, op, fix_null=fix)
        rows.append({
            "<P,S> = -(d^2-r^2)/2": (ip(P, S) + 0.5 * (d2 - r ** 2)).abs().max().item(),
            "S.S = r^2": (ip(S, S) - r ** 2).abs().max().item(),
            "<P,pi> = n.p - d": (ip(P, pi) - ((n * p).sum(-1) - d_plane)).abs().max().item(),
            "T(sphere) covariant": _rel(moved(S), embed_sphere(c + t, r, fix_null=fix)),
            "T(plane) covariant": _rel(moved(pi), embed_plane(n, c + t, fix_null=fix)),
            "T(circle) covariant": _rel(moved(C),
                                        embed_circle_ipns(c + t, n, r, op, fix_null=fix)),
        })

    print(f"\nConformal primitives (absolute deviation, tol {tol:g})")
    print(f"  {'':<24} {'as shipped':>10} {'--fix_cga_null':>16}")
    for key in rows[0]:
        print(f"  {key:<24} {rows[0][key]:>10.2e} {rows[1][key]:>16.2e}")

    ok = all(v < tol for v in rows[1].values())
    if not ok:
        print("  FAIL: the fixed primitives should satisfy all of these")
    return ok


def _rel(got, want):
    return ((got - want).abs().max() / want.abs().max().clamp(min=1e-30)).item()


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--theta", type=float, default=0.7)
    # In embedded units, where the model divides positions by pos_scale =
    # 1000 mm. This shift is therefore about 0.6 m, already large next to the
    # detector. The conformal residual grows polynomially with |t| -- a null
    # vector carries |p|^2, so a translation makes coefficients cancel across
    # several orders of magnitude (de Haan et al. Sec. 3.4, the reason C-GATr
    # needs 32-bit). That is conditioning, not a broken symmetry: a genuine
    # break stays O(1) however small the shift.
    p.add_argument("--shift", type=float, nargs=3, default=(0.31, -0.17, 0.44))
    a = p.parse_args()

    # The single-ingredient arms, then the cumulative ladder rungs as actually queued.
    # The rungs matter separately: `two_channel_dc` needs the drift-direction columns and
    # `use_time` inserts a column before them, so their combination is the one place a
    # feature-offset error could hide, and it is the combination every rung from v2_b on
    # is trained with. An offset error there would read the wrong columns as the drift
    # direction, which is not something the per-ingredient arms can catch.
    arms = [("conformal", {}),
            ("conformal + time", {"use_time": True}),
            ("conformal 2-channel", {"two_channel_dc": True}),
            ("conformal null-fixed", {"fix_cga_null": True}),
            ("conformal 2ch + fixed", {"two_channel_dc": True,
                                       "fix_cga_null": True}),
            ("conformal identity-init", {"equi_init": "identity_algebra"}),
            # Both wire-direction formulas put the azimuth in the transverse
            # part, so a rotation about z is a shift of that angle either way;
            # this pins that the corrected one keeps it.
            ("conformal wire-dir fixed", {"fix_cga_null": True,
                                          "fix_wire_dir": True}),
            ("conformal 2ch + wire-dir", {"fix_cga_null": True,
                                          "fix_wire_dir": True,
                                          "two_channel_dc": True}),
            ("v2_b_time (rung)", {"fix_cga_null": True, "use_time": True}),
            ("v2_c_twochan (rung)", {"fix_cga_null": True, "use_time": True,
                                     "two_channel_dc": True}),
            ("v2_d_init (rung)", {"fix_cga_null": True, "use_time": True,
                                  "two_channel_dc": True,
                                  "equi_init": "identity_algebra"}),
            ("projective", {"algebra": "projective"}),
            ("projective (GGTF enc)", {"algebra": "projective",
                                       "pga_hit_encoding": "ggtf"}),
            # The M39 control: the same pair plus the wire in a second channel.
            ("projective (GGTF + wire)", {"algebra": "projective",
                                          "pga_hit_encoding": "ggtf_wire"}),
            ("conformal physical constraints",
             {"fix_cga_null": True, "fix_wire_dir": True,
              "cga_hit_encoding": "sphere_plane",
              "physical_drift_geometry": True,
              "separate_hit_metadata": True}),
            ("projective physical point+line",
             {"algebra": "projective", "fix_wire_dir": True,
              "pga_hit_encoding": "point_line",
              "physical_drift_geometry": True,
              "separate_hit_metadata": True})]

    good = True
    print("\nRotation equivariance, embedding + backbone (relative error, tol 2e-4)")
    for name, kw in arms:
        model = CGATrParquetModel(base_args(**kw)).eval().double()
        good &= check(model, name, lambda f: rotate_features(a.theta, f),
                      rotor(model, a.theta))

    print("\nTranslation equivariance, backbone only (relative error, tol 2e-4)")
    for name, kw in arms:
        model = CGATrParquetModel(base_args(**kw)).eval().double()
        good &= check_backbone(model, name, translator(model, a.shift))

    print("\nReflection equivariance, E(3) CGA backbone (relative error, tol 2e-4)")
    from src.cgatr.primitives.linear import (
        _compute_grade_involution,
        _mirror_action_matrix,
    )
    e3_model = CGATrParquetModel(
        base_args(equivariance_group="e3")
    ).eval().double()
    mirror = _mirror_action_matrix(
        e3_model.basis_gp,
        _compute_grade_involution(),
        vector_idx=1,
    )
    good &= check_backbone_action(e3_model, "conformal E(3)", mirror)

    good &= check_primitives(a.shift)

    print("\nall requested equivariances passed" if good else "\nEQUIVARIANCE FAILURE")
    raise SystemExit(0 if good else 1)


if __name__ == "__main__":
    main()
